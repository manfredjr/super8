<h2>Quem trata seus dados</h2>
<p>MT - Manfred Tecnologia, responsavel pelo sistema Super 8.</p>

<h2>O que guardamos</h2>
<p>De quem cria conta: nome, e-mail, senha guardada de forma cifrada e irreversivel, e o endereco de origem no momento do aceite do termo de uso.</p>
<p>De quem e cadastrado como competidor sem conta: apenas o nome de exibicao informado por quem organiza o evento.</p>
<p>Dos eventos: nome, data, local, custo, os competidores inscritos e os placares das partidas.</p>

<h2>Por que guardamos</h2>
<p>Para o organizador, os dados existem para executar o servico que ele contratou ao criar a conta, que e o uso gratuito do sistema tendo a MT como apoiadora dos eventos dele.</p>
<p>Para o competidor cadastrado por terceiro, os dados existem pelo interesse legitimo de organizar o torneio: o nome aparece porque a pessoa esta jogando. A marca da MT esta na mesma pagina como patrocinadora do evento, do mesmo jeito que um banner de patrocinador aparece atras da quadra num torneio presencial. Nao usamos nome nem imagem de jogador em peca publicitaria.</p>

<h2>Com quem compartilhamos</h2>
<p>Com ninguem. Nao vendemos dado, nao cedemos para terceiros e nao alimentamos servico de publicidade com dado de quem usa o sistema.</p>

<h2>Por quanto tempo</h2>
<p>Enquanto a conta estiver ativa. Encerrada a conta, o nome e substituido por identificador anonimo e os placares permanecem como numero de evento.</p>

<h2>Seus direitos</h2>
<p>Voce pode pedir acesso aos seus dados, correcao e exclusao. O pedido pode ser feito pelo contato da MT - Manfred Tecnologia.</p>
