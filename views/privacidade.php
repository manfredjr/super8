<h2>Quem trata seus dados</h2>
<p>MT - Manfred Tecnologia, responsável pelo sistema Super 8.</p>

<h2>O que guardamos</h2>
<p>De quem cria conta: nome, e-mail, senha guardada de forma cifrada e irreversível, e o endereço de origem no momento do aceite do termo de uso.</p>
<p>De quem é cadastrado como competidor sem conta: apenas o nome de exibição informado por quem organiza o evento.</p>
<p>Dos eventos: nome, data, local, custo, os competidores inscritos e os placares das partidas.</p>

<h2>Por que guardamos</h2>
<p>Para o organizador, os dados existem para executar o serviço que ele contratou ao criar a conta, que é o uso gratuito do sistema tendo a MT como apoiadora dos eventos dele.</p>
<p>Para o competidor cadastrado por terceiro, os dados existem pelo interesse legítimo de organizar o torneio: o nome aparece porque a pessoa está jogando. A marca da MT está na mesma página como patrocinadora do evento, do mesmo jeito que um banner de patrocinador aparece atrás da quadra num torneio presencial. Não usamos nome nem imagem de jogador em peça publicitária.</p>

<h2>Com quem compartilhamos</h2>
<p>Com ninguém. Não vendemos dado, não cedemos para terceiros e não alimentamos serviço de publicidade com dado de quem usa o sistema.</p>

<h2>Por quanto tempo</h2>
<p>Enquanto a conta estiver ativa. Encerrada a conta, o nome é substituído por identificador anônimo e os placares permanecem como número de evento.</p>

<h2>Seus direitos</h2>
<p>Você pode pedir acesso aos seus dados, correção e exclusão. O pedido pode ser feito pelo contato da MT - Manfred Tecnologia.</p>
